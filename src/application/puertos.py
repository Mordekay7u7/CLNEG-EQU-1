"""Contratos abstractos para aislar aplicación de infraestructura."""
from abc import ABC,abstractmethod
class RepositorioCitas(ABC):
    @abstractmethod
    def obtener(self,identificador):...
    @abstractmethod
    def listar(self):...
    @abstractmethod
    def guardar(self,cita):...
class UnidadTrabajo(ABC):
    @abstractmethod
    def confirmar(self):...
    @abstractmethod
    def revertir(self):...
